/**
 * Build src/generated/chaosHeadline.ts from the designer's Figma outline
 * export of the ChaosZoom headline (assets/chaos-headline.svg — "From chaos
 * to AI-powered dispatch" as vector paths). The dive zooms the SVG viewBox
 * to ×430: font glyph rasterisation falls apart there in GPU Chrome, while
 * plain path geometry scales flawlessly in every engine — so the headline
 * ships as outlines, not live text.
 *
 * The module carries the joined path data plus the geometry the dive needs:
 * total width, the baseline (bottom of the caps, read from the "F"), and
 * the hyphen's ink box (the simple 5-command rectangle path).
 *
 * Run: node scripts/gen-chaos-headline.mjs   (re-run only if the SVG changes)
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const SRC = path.join(ROOT, "assets/chaos-headline.svg")
const OUT = path.join(ROOT, "src/generated/chaosHeadline.ts")

const TEXT = "From chaos to AI-powered dispatch"
const svg = fs.readFileSync(SRC, "utf8")

const ds = [...svg.matchAll(/\bd="([^"]+)"/g)].map((m) => m[1])
if (!ds.length) throw new Error("no paths found")

// numeric extent of the whole set (crude vertex scan — fine for extent: Inter
// outlines always have on-curve extremes on the axis-aligned bounds we need)
const nums = (d) => [...d.matchAll(/-?\d+(?:\.\d+)?/g)].map((m) => parseFloat(m[0]))
let maxX = -Infinity
for (const d of ds) {
  const xs = nums(d)
  for (let i = 0; i < xs.length; i += 2) maxX = Math.max(maxX, xs[i])
}

// the hyphen is the one trivial rectangle path: M x0 y0 V y1 H x1 V y0 H x0 Z
const hyphenD = ds.find((d) => /^M[-\d. ]+V[-\d. ]+H[-\d. ]+V[-\d. ]+H[-\d. ]+Z$/.test(d.trim()))
if (!hyphenD) throw new Error("hyphen rectangle path not found")
const h = nums(hyphenD) // [x0, y0, y1, x1, y0, x0]
const hyphen = {
  x0: Math.min(h[0], h[3]),
  x1: Math.max(h[0], h[3]),
  y0: Math.min(h[1], h[2]),
  y1: Math.max(h[1], h[2]),
}

// baseline = bottom of the caps: the "F" is the path that starts at x=0
const fD = ds.find((d) => /^M0 /.test(d.trim()))
if (!fD) throw new Error("F path not found")
const baseline = Math.max(...nums(fD).filter((_, i) => i % 2 === 1))

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(
  OUT,
  `/**
 * AUTO-GENERATED by scripts/gen-chaos-headline.mjs from assets/chaos-headline.svg
 * (the designer's Figma outline export) — do not edit.
 * "${TEXT}" as vector outlines; source coordinate space of the export.
 */
export const HEADLINE_TEXT = ${JSON.stringify(TEXT)}
export const HEADLINE_WIDTH = ${maxX}
/** baseline (bottom of the caps) in the source coordinate space */
export const HEADLINE_BASELINE = ${baseline}
/** hyphen ink box, source coordinate space */
export const HYPHEN_BOX = { x0: ${hyphen.x0}, x1: ${hyphen.x1}, y0: ${hyphen.y0}, y1: ${hyphen.y1} }
export const HEADLINE_D = ${JSON.stringify(ds.join(" "))}
`,
)
console.log("width", maxX, "baseline", baseline, "hyphen", hyphen)
